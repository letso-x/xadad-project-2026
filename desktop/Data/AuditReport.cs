using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using MzuApplication.Models;

namespace MzuApplication.Data
{
    /// <summary>
    /// Generates a polished, client-ready audit trail report as a self-contained HTML
    /// file with Mzukulu branding (shared via <see cref="ReportStyle"/>). Opens in any
    /// browser and prints cleanly to PDF for a handover pack.
    /// </summary>
    internal static class AuditReport
    {
        public static void Export(List<AuditEntry> entries, string path)
        {
            int checkd; AuditEntry broken;
            bool intact = Audit.VerifyIntegrity(out checkd, out broken);

            string company = ReportStyle.SafeCompany();
            DateTime now = DateTime.Now;

            var sb = new StringBuilder();
            sb.Append("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">");
            sb.Append("<title>Mzukulu QMS — Audit Trail Report</title>");
            sb.Append("<style>").Append(ReportStyle.Css(true)).Append("</style></head><body>");

            sb.Append(ReportStyle.Band("Audit Trail Report"));

            sb.Append("<div class=\"meta\">");
            sb.Append(ReportStyle.MetaItem("Organisation", company));
            sb.Append(ReportStyle.MetaItem("Generated", now.ToString("dd MMMM yyyy, HH:mm")));
            sb.Append(ReportStyle.MetaItem("Generated by", Repository.CurrentUserName ?? "system"));
            sb.Append(ReportStyle.MetaItem("Workstation", ReportStyle.SafeHost()));
            sb.Append(ReportStyle.MetaItem("Total events", entries.Count.ToString(CultureInfo.InvariantCulture)));
            sb.Append("<div class=\"metaitem\"><div class=\"mlabel\">Chain integrity</div>"
                + "<div class=\"mvalue\">"
                + (intact
                    ? "<span class=\"badge ok\">&#10003; VERIFIED &middot; untampered</span>"
                    : "<span class=\"badge bad\">&#9888; BROKEN &middot; review required</span>")
                + "</div></div>");
            sb.Append("</div>");

            sb.Append("<div class=\"section\">");
            sb.Append("<table><thead><tr>"
                + "<th>When</th><th>User</th><th>Action</th><th>Document / Entity</th>"
                + "<th>Context</th><th>Detail</th><th>From</th></tr></thead><tbody>");

            foreach (AuditEntry e in entries)
            {
                DateTime at = e.At.Kind == DateTimeKind.Utc ? e.At.ToLocalTime() : e.At;
                sb.Append("<tr>");
                sb.Append(Td(at.ToString("yyyy-MM-dd HH:mm"), "mono nowrap"));
                sb.Append("<td><div class=\"u\">").Append(ReportStyle.Enc(e.User))
                  .Append("</div><div class=\"sub\">").Append(ReportStyle.Enc(Format.RoleName(e.Role)))
                  .Append("</div></td>");
                sb.Append("<td>").Append(ActionPill(e.Action)).Append("</td>");
                sb.Append("<td><div class=\"u\">").Append(ReportStyle.Enc(e.EntityLabel ?? "—"))
                  .Append("</div><div class=\"sub\">").Append(ReportStyle.Enc(e.EntityType ?? string.Empty))
                  .Append("</div></td>");
                sb.Append(Td(string.IsNullOrEmpty(e.Context) ? "—" : e.Context, null));
                sb.Append(Td(e.Detail ?? string.Empty, null));
                sb.Append(Td(string.IsNullOrEmpty(e.Host) ? "—" : e.Host, "mono sub"));
                sb.Append("</tr>");
            }

            sb.Append("</tbody></table></div>");

            sb.Append("<div class=\"foot\"><div>This audit trail is append-only and "
                + "tamper-evident. Each entry is chained with SHA-256; the integrity status "
                + "above reflects verification at the time of export.</div>");
            sb.Append("<div class=\"footbrand\">" + ReportStyle.Enc(company)
                + " &middot; Generated " + now.ToString("yyyy-MM-dd HH:mm") + "</div></div>");

            sb.Append("</body></html>");

            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));

            Audit.Log(AuditAction.Exported, "Audit", null, entries.Count + " entries",
                "Exported branded audit report (" + (intact ? "chain verified" : "chain WARNING") + ")");
        }

        private static string Td(string text, string cls)
        {
            return cls == null
                ? "<td>" + ReportStyle.Enc(text) + "</td>"
                : "<td class=\"" + cls + "\">" + ReportStyle.Enc(text) + "</td>";
        }

        private static string ActionPill(AuditAction action)
        {
            string cls;
            switch (action)
            {
                case AuditAction.NcrRaised:
                case AuditAction.Deleted:
                    cls = "p-red"; break;
                case AuditAction.Submitted:
                case AuditAction.SignedOff:
                case AuditAction.NcrClosed:
                    cls = "p-green"; break;
                case AuditAction.SignedIn:
                    cls = "p-navy"; break;
                default:
                    cls = "p-slate"; break;
            }
            return "<span class=\"pill " + cls + "\">" + ReportStyle.Enc(Audit.ActionText(action)) + "</span>";
        }
    }
}
